export function createSampleBudgetFile(
  fileName: string = 'Presupuesto_Creditos_2026_Ley.xlsx',
  modificationFactor: number = 1.0,
  uploadedAt: string = '2026-03-01T09:00:00.000Z'
): BudgetFile {
  const headers = [
    'FUENTE FINANCIAMIENTO',
    'INCISO',
    'PARTIDA PRINCIPAL',
    'PARTIDA PARCIAL',
    'PARTIDA SUBPARCIAL',
    'DESCRIPCIÓN',
    'SANCIÓN',
    'VIGENTE',
    'RESTRINGIDO',
    'PREVENTIVO',
    'DEFINITIVO',
    'DEVENGADO',
    'PROGRAMA',
    'JURISDICCIÓN',
  ];

  const columnMapping: Record<string, string> = {
    fuenteFinanciamiento: 'FUENTE FINANCIAMIENTO',
    inciso: 'INCISO',
    partidaPrincipal: 'PARTIDA PRINCIPAL',
    partidaParcial: 'PARTIDA PARCIAL',
    partidaSubparcial: 'PARTIDA SUBPARCIAL',
    descripcion: 'DESCRIPCIÓN',
    sancion: 'SANCIÓN',
    vigente: 'VIGENTE',
    restringido: 'RESTRINGIDO',
    preventivo: 'PREVENTIVO',
    definitivo: 'DEFINITIVO',
    devengado: 'DEVENGADO',
  };

  const rows: BudgetRow[] = BASE_SAMPLE_ROWS.map((row, idx) => {
    // If modificationFactor differs, simulate credit increments / execution variations
    const vig = Math.round(row.vigente * modificationFactor);
    const prev = Math.round(row.preventivo * (modificationFactor > 1 ? 1.08 : 1.0));
    const def = Math.round(row.definitivo * (modificationFactor > 1 ? 1.12 : 1.0));
    const dev = Math.round(row.devengado * (modificationFactor > 1 ? 1.15 : 1.0));

    const rawData: Record<string, any> = {
      'FUENTE FINANCIAMIENTO': row.ff,
      'INCISO': row.inciso,
      'PARTIDA PRINCIPAL': row.pp,
      'PARTIDA PARCIAL': row.parcial,
      'PARTIDA SUBPARCIAL': row.subparcial,
      'DESCRIPCIÓN': row.desc,
      'SANCIÓN': row.sancion,
      'VIGENTE': vig,
      'RESTRINGIDO': row.restringido,
      'PREVENTIVO': prev,
      'DEFINITIVO': def,
      'DEVENGADO': dev,
      'PROGRAMA': row.programa || '',
      'JURISDICCIÓN': row.jurisdiccion || '',
    };

    return {
      id: `sample-${idx + 1}-${Math.round(modificationFactor * 100)}`,
      fuenteFinanciamiento: row.ff,
      inciso: row.inciso,
      partidaPrincipal: row.pp,
      partidaParcial: row.parcial,
      partidaSubparcial: row.subparcial,
      descripcion: row.desc,
      sancion: row.sancion,
      vigente: vig,
      restringido: row.restringido,
      preventivo: prev,
      definitivo: def,
      devengado: dev,
      raw: rawData,
    };
  });

  return {
    id: `file-${fileName.replace(/[^a-zA-Z0-9]/g, '_')}`,
    fileName,
    uploadedAt,
    rowCount: rows.length,
    headers,
    columnMapping,
    rows,
    fileSize: 45200,
  };
}

